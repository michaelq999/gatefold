/* Writes src/css/fonts.css with both typefaces embedded as data, so the app
   never loads a font from another site.

   - TeX Gyre Bonum Regular: embedded byte-for-byte as distributed
     (GUST Font License, src/fonts/GUST-FONT-LICENSE.txt).
   - Inter Regular / Medium / SemiBold: reduced to Latin, Greek and Cyrillic
     characters (SIL Open Font License 1.1, src/fonts/OFL-1.1.txt). */
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'src', 'fonts');
const out = path.join(__dirname, '..', 'src', 'css', 'fonts.css');
const b64 = (file) => fs.readFileSync(path.join(dir, file)).toString('base64');

const faces = [
  { family: 'TeX Gyre Bonum', weight: 400, file: 'texgyrebonum-regular.otf', mime: 'font/otf', format: 'opentype' },
  { family: 'Inter', weight: 400, file: 'Inter-Regular.subset.woff', mime: 'font/woff', format: 'woff' },
  { family: 'Inter', weight: 500, file: 'Inter-Medium.subset.woff', mime: 'font/woff', format: 'woff' },
  { family: 'Inter', weight: 600, file: 'Inter-SemiBold.subset.woff', mime: 'font/woff', format: 'woff' }
];

let css = `/* Generated by tools/make-fonts.js. Do not edit by hand.
   TeX Gyre Bonum: (c) GUST e-foundry, GUST Font License. Embedded unmodified.
   Inter: Copyright 2016 The Inter Project Authors, SIL Open Font License 1.1. Subset. */\n`;
for (const f of faces) {
  css += `@font-face{font-family:"${f.family}";font-style:normal;font-weight:${f.weight};font-display:swap;` +
    `src:url(data:${f.mime};base64,${b64(f.file)}) format("${f.format}")}\n`;
}
fs.writeFileSync(out, css);
console.log('fonts.css', Math.round(css.length / 1024) + ' KB');
